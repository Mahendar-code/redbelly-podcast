"""Write CLIPS.md (deliverable 2) and VERIFICATION.md from clips.json and verification/report.json.

usage: docs.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def ts(t):
    m, s = divmod(t, 60)
    return f"{int(m):02d}:{s:04.1f}"


def length(c):
    return round(c["end"] - c["start"])


def clips_md(cfg):
    eps = cfg["episodes"]
    out = [
        "# Clip list",
        "",
        "Six vertical clips cut from the most recent official Redbelly Insights episodes published at "
        "[redbelly.network/ama](https://redbelly.network/ama). Every clip is one continuous passage of the episode: "
        "nothing inside a clip has been cut, reordered or joined.",
        "",
        "Timestamps are `mm:ss.s` from the start of the official episode video linked in each entry. "
        "Each link opens the episode at the start of the clip.",
        "",
        "| # | Clip | Source episode | Source timestamp | Length | Speaker | Suggested post caption |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, c in enumerate(cfg["clips"], 1):
        ep = eps[c["episode"]]
        out.append(
            f"| {i} | [`{c['id']}.mp4`](clips/{c['id']}.mp4) | {ep['title']} ({ep['date']}) | "
            f"[{ts(c['start'])} to {ts(c['end'])}]({ep['url']}#t={c['start']:.1f},{c['end']:.1f}) | {length(c)} s | "
            f"{c['speaker']}, {c['role']} | {c['caption']} |")
    out += ["", "## Details", ""]
    for i, c in enumerate(cfg["clips"], 1):
        ep = eps[c["episode"]]
        out += [
            f"### {i}. {c['hook']}",
            "",
            f"- **File:** [`clips/{c['id']}.mp4`](clips/{c['id']}.mp4), subtitles burned in and also in "
            f"[`subtitles/{c['id']}.srt`](subtitles/{c['id']}.srt)",
            f"- **Source:** {ep['title']}, {ep['date']}. Official episode video: {ep['url']}",
            f"- **Source timestamp:** {ts(c['start'])} to {ts(c['end'])} ({c['start']:.2f} s to {c['end']:.2f} s), "
            f"{length(c)} seconds",
            f"- **Speaker:** {c['speaker']}, {c['role']} (role as listed at {c['role_source']})",
            f"- **Topic:** {c['topic']}",
            f"- **The one point:** {c['point']}",
            f"- **Suggested post caption:** {c['caption']}",
        ]
        for note in c.get("notes", []):
            out.append(f"- **Note:** {note}")
        out += ["", "Subtitle text, word for word:", "", f"> {c['text']}", ""]
    return "\n".join(out)


def verification_md(cfg, report):
    out = [
        "# Verification",
        "",
        f"Generated by `python3 tools/verify.py` from the files in `clips/` and `subtitles/`. "
        f"Every value is measured from the rendered MP4 and SRT files, not typed by hand.",
        "",
        f"**Result: {report['result']}** ({report['mode']} run, {len(report['failures'])} failed checks)",
        "",
        "## Specs and loudness",
        "",
        "| Clip | Resolution | Frame rate | Codecs | Length | Size | Loudness | True peak | LRA |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in report["clips"]:
        p, L = r["probe"], r["loudness"]
        out.append(f"| {r['id']} | {p['width']}x{p['height']} | {p['fps']:g} fps | {p['vcodec']} + {p['acodec']} | "
                   f"{p['duration']:.1f} s | {p['size_mb']} MB | {L['lufs']:.1f} LUFS | {L['true_peak']:.1f} dBTP | "
                   f"{L['lra']:.1f} LU |")
    out += ["", "## Checks per clip", ""]
    names = list(report["clips"][0]["checks"])
    for r in report["clips"]:
        out += [f"### {r['id']}", "", "| Check | Result | Measured |", "|---|---|---|"]
        for n in names:
            v = r["checks"][n]
            out.append(f"| {n} | {'PASS' if v['pass'] else 'FAIL'} | {v['value']} |")
        out.append("")
    if any("independent_differences" in r for r in report["clips"]):
        out += ["## Subtitles against the independent transcript", "",
                f"Every place where `{cfg['verify_model']}` reads a finished clip differently from its subtitles, "
                "written as `subtitle / model`. A dash means nothing on that side.", ""]
        for r in report["clips"]:
            diffs = r.get("independent_differences", [])
            out.append(f"- **{r['id']}:** " + ("; ".join(f"`{d}`" for d in diffs) if diffs else "no differences"))
        out.append("")
    out += ["## Pack", "", "| Check | Result | Measured |", "|---|---|---|"]
    for n, v in report["pack"].items():
        val = v["value"] if not isinstance(v["value"], list) else "; ".join(map(str, v["value"]))
        out.append(f"| {n} | {'PASS' if v['pass'] else 'FAIL'} | {val} |")
    out += [
        "",
        "## What each check means",
        "",
        "- **Audio matches stated source timestamp:** the first 10 seconds of each clip's audio are cross-correlated "
        "with the official episode around the timestamp given in `CLIPS.md`. An offset of zero proves the timestamp "
        "points at exactly this audio.",
        "- **Subtitles = proof-read text:** the words in the SRT file are the proof-read text in `clips.json`, "
        "word for word.",
        f"- **Subtitles vs independent transcript:** each finished clip is transcribed again with Whisper "
        f"`{cfg['verify_model']}`, a fourth model that was not used to make the subtitles, and compared with the "
        "subtitle text. The word error rate is measured after folding Australian and US spellings together "
        "(-ise and -ize endings), reading \"+\" as \"plus\", joining split compounds (guard rails, guardrails), and "
        "dropping fillers and stammered repeats, which clean verbatim subtitles leave out. The raw rate is shown "
        "beside it, and every remaining difference is listed below so it can be checked by ear.",
        "- **Every spoken word inside a cue:** each timed word falls inside the time range of a subtitle cue.",
        "- **Speaker in frame:** five frames per second of the finished clip are checked with face detection (YuNet) "
        "and face recognition (SFace) against reference frames of the named speaker.",
        "- **Names, terms, credits, dashes:** subtitles, docs and the page are searched for misspellings of "
        "Redbelly terms and names, for personal credits or handles, and for en or em dashes and emoji, which the "
        "Redbelly DAO brand kit rules out.",
        "",
    ]
    return "\n".join(out)


def main():
    cfg = json.loads((ROOT / "clips.json").read_text())
    (ROOT / "CLIPS.md").write_text(clips_md(cfg) + "\n", encoding="utf-8")
    report_path = ROOT / "verification" / "report.json"
    if report_path.exists():
        report = json.loads(report_path.read_text())
        (ROOT / "VERIFICATION.md").write_text(verification_md(cfg, report) + "\n", encoding="utf-8")
    print("wrote CLIPS.md" + (" and VERIFICATION.md" if report_path.exists() else ""))


if __name__ == "__main__":
    main()
